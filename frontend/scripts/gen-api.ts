// Generates the typed API client surface from the backend's per-Area Swagger documents.
//
// Run with `pnpm gen:api` (online, default) while the API runs in Development, or
// `pnpm gen:api --offline` to regenerate types from the committed `openapi/*.json` snapshots without a
// running API or SQL Server.
//
// Node 24 runs this file directly (native type stripping — Probe 13). Only erasable TypeScript syntax is
// used here: no `enum`, no `namespace`, no parameter properties.
import { writeFile, readFile } from 'node:fs/promises'
import ts from 'typescript'
import openapiTS, { astToString } from 'openapi-typescript'

const areas = ['agent', 'portal', 'admin', 'public'] as const
type Area = (typeof areas)[number]

// A multipart file part (Story 58: the logo upload) is a Blob in the browser, not the default string.
const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier('Blob'))
function transform(schema: { format?: string }): ts.TypeNode | undefined {
  return schema.format === 'binary' ? BLOB : undefined
}

const offline = process.argv.includes('--offline')
const apiUrl = process.env.CRM_API_URL ?? 'http://localhost:5187'

const openapiDir = new URL('../openapi/', import.meta.url)
const generatedDir = new URL('../app/api/generated/', import.meta.url)

async function fetchDocument(area: Area): Promise<unknown> {
  const url = new URL(`/swagger/${area}/swagger.json`, apiUrl)
  let response: Response
  try {
    response = await fetch(url)
  } catch {
    throw new Error(
      `gen:api: cannot reach ${url.toString()}. Start the API in Development (dotnet run --project backend/src/Crm.Api) or use --offline.`,
    )
  }
  if (!response.ok) {
    throw new Error(
      `gen:api: cannot reach ${url.toString()}. Start the API in Development (dotnet run --project backend/src/Crm.Api) or use --offline.`,
    )
  }
  return response.json()
}

async function readSnapshot(area: Area): Promise<unknown> {
  const path = new URL(`${area}.json`, openapiDir)
  const raw = await readFile(path, 'utf-8')
  return JSON.parse(raw)
}

function countPaths(doc: unknown): number {
  if (typeof doc !== 'object' || doc === null) return 0
  const paths = (doc as Record<string, unknown>)['paths']
  if (typeof paths !== 'object' || paths === null) return 0
  return Object.keys(paths).length
}

async function main(): Promise<void> {
  const documents = new Map<Area, unknown>()

  if (offline) {
    for (const area of areas) {
      documents.set(area, await readSnapshot(area))
    }
  } else {
    // Fetch all four before writing anything: never leave a half-written set on a mid-run failure.
    for (const area of areas) {
      documents.set(area, await fetchDocument(area))
    }
    for (const area of areas) {
      const path = new URL(`${area}.json`, openapiDir)
      await writeFile(path, JSON.stringify(documents.get(area), null, 2) + '\n', 'utf-8')
    }
  }

  for (const area of areas) {
    const jsonPath = new URL(`${area}.json`, openapiDir)
    // jsonPath is already a file:// URL; openapiTS reads it straight off disk (Probe 13: it never needs
    // the API to be running when --offline was used, and always reads the file it just wrote otherwise).
    const ast = await openapiTS(jsonPath, { transform })
    const banner = `// Generated by pnpm gen:api from openapi/${area}.json. Do not edit.\n`
    const body = banner + astToString(ast)
    const outPath = new URL(`${area}.ts`, generatedDir)
    await writeFile(outPath, body, 'utf-8')
    console.log(`gen:api: ${area} -> ${countPaths(documents.get(area))} path(s)`)
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : String(error))
  process.exit(1)
})
